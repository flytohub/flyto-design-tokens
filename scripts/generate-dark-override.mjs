/**
 * Generate `css/tokens-dark.css` from `css/tokens.css` and `css/tokens-light.css`.
 *
 * The dark-override file exists because `tokens.css` puts the dark values on
 * `:root` — correct for a dark-only product — while a dual-mode product imports
 * `tokens-light.css` after it and needs the dark values back under a dark
 * selector.
 *
 * It is generated rather than written because it is, by definition, a second
 * copy of values that already exist. Hand-maintaining it would reintroduce
 * exactly the drift this package exists to prevent, one forgotten value at a
 * time. The rule it encodes is mechanical and worth stating plainly:
 *
 *   the dark override restates precisely the names `tokens-light.css`
 *   redefines, with precisely the values `tokens.css` gives them
 *
 * so a token that gains a light value automatically gains a dark override, and
 * a dark value that changes carries into the override on the next generate.
 *
 *   node scripts/generate-dark-override.mjs
 *   node scripts/generate-dark-override.mjs --check
 */
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const check = process.argv.includes('--check')

const darkSource = await readFile(resolve(root, 'css/tokens.css'), 'utf8')
const lightSource = await readFile(resolve(root, 'css/tokens-light.css'), 'utf8')
const outputPath = resolve(root, 'css/tokens-dark.css')

/* Comments are stripped rather than avoided by anchoring the match to the start
 * of a line. Anchoring looks equivalent and is not: it silently misses a
 * single-line `:root { --flyto-x: #fff; }`, which is legal CSS this repo writes
 * elsewhere, so a token declared that way would never gain a dark override and
 * would stay light in dark mode with nothing failing. */
const withoutComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, ' ')

const declarations = (css) => {
  const found = new Map()
  for (const [, name, value] of withoutComments(css).matchAll(
    /(--flyto-[\w-]+)\s*:\s*([^;}]+)[;}]/g,
  )) {
    if (!found.has(name)) found.set(name, value.trim().replace(/\s+/g, ' '))
  }
  return found
}

const darkValues = declarations(darkSource)
const lightNames = [...declarations(lightSource).keys()]

const missing = lightNames.filter((name) => !darkValues.has(name))
if (missing.length) {
  process.stderr.write(
    `tokens-light.css redefines ${missing.length} name(s) that tokens.css does ` +
      `not declare, so there is no dark value to restore:\n  ${missing.join('\n  ')}\n`,
  )
  process.exit(1)
}

const body = lightNames.map((name) => `  ${name}: ${darkValues.get(name)};`).join('\n')

const output = `/* =========================================================================
   @flyto2/design-tokens — dark palette, re-asserted under a dark selector
   =========================================================================

   \`css/tokens.css\` puts the dark values on \`:root\`, which is right for a
   dark-only product. A product with both modes imports \`css/tokens-light.css\`
   after it, which moves the semantic roles to light on \`:root\` — and then needs
   the dark values back under whatever selector marks dark mode.

   That is all this file is. It re-states exactly the names \`tokens-light.css\`
   redefines, with exactly the values \`tokens.css\` gives them, under the two
   selectors in common use: a \`.dark\` class (Tailwind and UnoCSS class strategy)
   and \`[data-theme="dark"]\`.

   Import order matters and is the whole contract:

     @import '@flyto2/design-tokens/css';           // ramps + dark defaults
     @import '@flyto2/design-tokens/css/light';     // roles become light
     @import '@flyto2/design-tokens/css/dark';      // roles go dark again under .dark

   Generated by \`scripts/generate-dark-override.mjs\`; \`npm run docs:check\` fails
   if it is stale, so it cannot drift from the values it mirrors.
   ========================================================================= */

.dark,
[data-theme="dark"] {
  color-scheme: dark;

${body}
}
`

if (check) {
  let current = ''
  try {
    current = await readFile(outputPath, 'utf8')
  } catch {
    // Treated as drift below.
  }
  if (current !== output) {
    process.stderr.write(
      'css/tokens-dark.css is stale; run node scripts/generate-dark-override.mjs\n',
    )
    process.exitCode = 1
  } else {
    process.stdout.write(`dark override: PASS (${lightNames.length} tokens mirrored)\n`)
  }
} else {
  await writeFile(outputPath, output)
  process.stdout.write(`dark override: ${outputPath} (${lightNames.length} tokens)\n`)
}
